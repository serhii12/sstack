#!/usr/bin/env node
// triage-check: checks the triage labels and the triage comments of issues after triage.
//
// The roles come from mattpocock/skills skills/engineering/triage/SKILL.md (MIT,
// Copyright (c) 2026 Matt Pocock, see NOTICE): two category roles, five state roles,
// "exactly one category role and one state role", the AI line at the top of every
// triage comment, and the agent brief, triage notes and out-of-scope rules.
// The checks and the P0 to P3 priority rule are new code.
//
// Two kinds of input:
//   - Local report files (a local tracker), such as .scratch/reports/03-export-fails.md.
//     The file has one `Status:` line (open or closed) and one `Labels:` line.
//   - One issue or pull request as JSON from the tracker tool, read from a file or from stdin (`-`):
//       gh issue view <n> --json number,labels,state,comments
//       gh pr view <n> --json number,labels,state,comments
//       glab issue view <n> --comments -F json
//     `labels` is a list of names or of { name }. `state` is open, opened, closed or merged.
//     A merged pull request counts as closed.
//     `comments` (or `notes`) is a list of strings or of { body }. Only comments count as
//     triage output. The issue body is the report, so a brief inside it does not count.
//     The glab shape was not checked against a real glab.
//
// Label mapping: a repo can use its own label names. `docs/agents/triage-labels.md` under the
// root maps each role to the label in the tracker, in a table `| Role | Label in this tracker | ... |`.
// The check reads that file when it exists, or the file that `--labels <file>` names. It maps each
// tracker label to its role before the rules below. The idea and the table come from
// mattpocock/skills skills/engineering/setup-matt-pocock-skills/triage-labels.md.
//
// Rules, for each issue:
//   category     exactly one of bug, enhancement
//   state        exactly one of needs-triage, needs-info, ready-for-agent, ready-for-human, wontfix
//   priority     at most one of P0, P1, P2, P3
//   disclaimer   the AI line comes right before every triage heading
//                (Agent Brief, Triage Notes, Triage Decision)
//   brief        ready-for-agent and ready-for-human need an Agent Brief with at least one
//                `- [ ]` item under an `Acceptance checks` heading
//   human        ready-for-human needs a `Why a human:` line in the brief
//   notes        needs-info needs Triage Notes with at least one item under "What we still need"
//   decision     wontfix needs a Triage Decision with a `Decision:` line
//   closed       wontfix needs a closed issue
//   out-of-scope a rejected enhancement names a `.out-of-scope/<concept>.md` file that exists
//   status       (local) exactly one `Status:` line that says open or closed
//   labels       (local) exactly one `Labels:` line
//   blocked-by   (local) ready-for-agent needs one `Blocked by:` line that /build can read: `none`,
//                or ticket files that exist in the folder of the report (a name such as `#12` fails)
//   placement    (local) a triage heading sits below the last `## Comments` heading. Text above it
//                is the report, so a brief there is not triage output
//   decision     the `Decision:` line names one of the three wontfix cases
//
// The skill folder ships to projects, so this file runs from the project root as
//   node .claude/skills/triage/scripts/triage-check.mjs [--labels <file>] <report.md>...
//   node .claude/skills/triage/scripts/triage-check.mjs [--labels <file>] --json <file | ->
// In the stack repo it is skills/triage/scripts/triage-check.mjs.
//
// Exit codes:
//   0  every issue passes
//   1  a rule is broken
//   2  usage error
//   3  an input cannot be read, the JSON is not an issue, or the label mapping cannot be read

import { existsSync, readFileSync, realpathSync, statSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const USAGE = "Usage: node .claude/skills/triage/scripts/triage-check.mjs [--labels <file>] <report.md>... | [--labels <file>] --json <file | ->";
export const LABEL_MAP_FILE = "docs/agents/triage-labels.md";
export const EXIT = { OK: 0, PROBLEMS: 1, USAGE: 2, INPUT: 3 };
export const CATEGORIES = ["bug", "enhancement"];
export const STATES = ["needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "wontfix"];
export const PRIORITIES = ["P0", "P1", "P2", "P3"];
export const AI_LINE = "> *This was generated by AI during triage.*";

const AI_LINE_RE = /^\s*>\s*[*_]?This was generated by AI during triage\.[*_]?\s*$/;
const TRIAGE_HEADING = /^(#{1,6})\s+(Agent Brief|Triage Notes|Triage Decision)\s*$/i;
const HEADING = /^(#{1,6})\s+(.*?)\s*$/;
const CHECKBOX = /^\s*[-*]\s+\[[ xX]\]\s+\S/;
const LIST_ITEM = /^\s*(?:[-*]|\d+\.)\s+\S/;
const key = (name) => new RegExp(`^\\s*(?:[-*]\\s+)?(?:\\*\\*)?${name}:(?:\\*\\*)?\\s*(.*?)\\s*$`, "i");
const STATUS = key("Status");
const LABELS = key("Labels");
const BLOCKED_BY = key("Blocked by");
const WHY_HUMAN = key("Why a human");
const DECISION = key("Decision");
const NONE = /^none(?:\s*\([^)]*\))?\.?$/i;

/** One entry of a `Blocked by:` list, reduced to a path. The same forms as skills/build/scripts/ticket-ready.mjs. */
function blockerTarget(entry) {
  let e = entry.trim().replace(/^`+|`+$/g, "").trim();
  const link = e.match(/^\[[^\]]*\]\(([^)\s]+)\)$/);
  if (link) e = link[1];
  return e.replace(/^\.\//, "");
}

export class InputError extends Error {
  constructor(message, fix = "pass a readable report file, or the output of `gh issue view <n> --json number,labels,state,comments`") {
    super(message);
    this.fix = fix;
  }
}

/** Lines with a flag for "inside a fenced code block". Fence lines count as inside. */
function scan(text) {
  const raw = String(text).replace(/^\uFEFF/, "").split(/\r?\n/);
  let open = null;
  return raw.map((t, i) => {
    const m = t.match(/^\s*(`{3,}|~{3,})(.*)$/);
    if (open === null) {
      if (m && !(m[1][0] === "`" && m[2].includes("`"))) {
        open = { ch: m[1][0], len: m[1].length };
        return { n: i + 1, t, fence: true };
      }
      return { n: i + 1, t, fence: false };
    }
    if (m && m[1][0] === open.ch && m[1].length >= open.len && m[2].trim() === "") open = null;
    return { n: i + 1, t, fence: true };
  });
}

/**
 * Find the triage blocks in one text. A block runs from its heading to the next heading
 * of the same or a higher level. `lineOffset` maps block lines to lines of the whole input.
 */
export function findBlocks(text, lineOffset = 0) {
  const lines = scan(text);
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (l.fence) continue;
    const m = l.t.match(TRIAGE_HEADING);
    if (!m) continue;
    const level = m[1].length;
    const body = [];
    for (let j = i + 1; j < lines.length; j++) {
      const h = lines[j].fence ? null : lines[j].t.match(HEADING);
      if (h && h[1].length <= level) break;
      body.push(lines[j]);
    }
    let prev = null;
    for (let j = i - 1; j >= 0; j--) {
      if (lines[j].t.trim() !== "") {
        prev = lines[j];
        break;
      }
    }
    blocks.push({
      kind: m[2].toLowerCase(),
      line: l.n + lineOffset,
      level,
      body,
      hasAiLine: prev !== null && !prev.fence && AI_LINE_RE.test(prev.t),
    });
  }
  return blocks;
}

/** True when a heading that matches `title` in the block is followed by at least one item that matches `item`. */
function sectionHasItem(block, title, item) {
  for (let i = 0; i < block.body.length; i++) {
    const l = block.body[i];
    if (l.fence) continue;
    const h = l.t.match(HEADING);
    const isTitle = h ? title.test(h[2]) : title.test(l.t.replace(/[*_:]/g, "").trim());
    if (!isTitle) continue;
    const level = h ? h[1].length : 7;
    let j = i + 1;
    for (; j < block.body.length; j++) {
      const x = block.body[j];
      if (x.fence) continue;
      const hh = x.t.match(HEADING);
      if (hh && hh[1].length <= level) break;
      if (!h && hh) break;
      if (item.test(x.t)) return true;
    }
    // A later title inside this range would scan a part of it again. Skip them, so the cost stays linear.
    i = j - 1;
  }
  return false;
}

function blockLine(block, re) {
  return block.body.find((l) => !l.fence && re.test(l.t)) ?? null;
}

/**
 * Check one issue. `issue` is { name, labels: string[], closed: boolean, blocks, local, extra }.
 * Returns a list of problems { line, rule, message, fix }.
 */
export function checkIssue(issue) {
  const problems = [];
  const add = (line, rule, message, fix) => problems.push({ line, rule, message, fix });
  const has = (list) => list.filter((x) => issue.labels.some((l) => l.toLowerCase() === x.toLowerCase()));
  const cats = has(CATEGORIES);
  const states = has(STATES);
  const prios = has(PRIORITIES);
  const labelLine = issue.labelLine ?? 1;

  if (cats.length !== 1) {
    add(labelLine, "category", cats.length === 0 ? "The issue has no category label" : `The issue has ${cats.length} category labels (${cats.join(", ")})`, "give it exactly one of `bug` or `enhancement`.");
  }
  if (states.length !== 1) {
    add(labelLine, "state", states.length === 0 ? "The issue has no state label" : `The issue has ${states.length} state labels (${states.join(", ")})`, `give it exactly one of ${STATES.map((s) => `\`${s}\``).join(", ")}. Remove the old state when you add the new one.`);
  }
  if (prios.length > 1) {
    add(labelLine, "priority", `The issue has ${prios.length} priority labels (${prios.join(", ")})`, "keep one of `P0`, `P1`, `P2` or `P3`, or none.");
  }

  for (const b of issue.blocks) {
    if (b.outside && b.hasAiLine) {
      add(b.line, "placement", `The triage heading on line ${b.line} is above the \`## Comments\` heading, so it is part of the report`, "append the triage comment under the last `## Comments` heading at the end of the file. Create the heading if it is missing.");
    } else if (!b.hasAiLine) {
      add(b.line, "disclaimer", `The triage heading on line ${b.line} has no AI line right above it`, `put \`${AI_LINE}\` on the line before the heading. If the reporter wrote this heading, it is not triage output.`);
    }
  }
  const ours = issue.blocks.filter((b) => b.hasAiLine && !b.outside);
  const briefs = ours.filter((b) => b.kind === "agent brief");
  const notes = ours.filter((b) => b.kind === "triage notes");
  const decisions = ours.filter((b) => b.kind === "triage decision");
  const state = states.length === 1 ? states[0].toLowerCase() : null;

  if (state === "ready-for-agent" || state === "ready-for-human") {
    const brief = briefs.at(-1);
    if (!brief) {
      add(labelLine, "brief", `The issue is \`${state}\` and has no Agent Brief`, "post an Agent Brief from BRIEF.md, with the AI line above its heading.");
    } else {
      if (!sectionHasItem(brief, /^Acceptance checks$/i, CHECKBOX)) {
        add(brief.line, "brief", "The Agent Brief has no `- [ ]` item under an `Acceptance checks` heading", "add `### Acceptance checks` with at least one `- [ ] <check>` line.");
      }
      if (state === "ready-for-human" && !blockLine(brief, WHY_HUMAN)?.t.match(WHY_HUMAN)[1]) {
        add(brief.line, "human", "The issue is `ready-for-human` and its brief has no `Why a human:` line", "add `Why a human: <the judgment, access or manual test that an agent cannot do>`.");
      }
    }
    if (state === "ready-for-agent" && issue.local) {
      const lines = issue.blockedBy;
      const fix = "keep one `Blocked by:` line near the top, with `none` or a comma-separated list of ticket files in the folder of this file.";
      if (lines.length === 0) {
        add(labelLine, "blocked-by", "The local issue is `ready-for-agent` and has no `Blocked by:` line", "add `Blocked by: None (can start immediately)`, or the blocking ticket files, near the top of the file.");
      } else if (lines.length > 1) {
        add(lines[1].n, "blocked-by", `The file has ${lines.length} \`Blocked by:\` lines`, fix);
      } else if (lines[0].value === "") {
        add(lines[0].n, "blocked-by", "The `Blocked by:` line is empty", fix);
      } else if (!NONE.test(lines[0].value)) {
        const names = lines[0].value.split(/\s*,\s*/).map(blockerTarget);
        if (names.some((x) => x === "" || NONE.test(x))) {
          add(lines[0].n, "blocked-by", "The `Blocked by:` line mixes `none` or an empty entry with ticket names", fix);
        } else {
          for (const n of names) {
            const f = resolve(issue.dir ?? ".", n);
            if (!(existsSync(f) && statSync(f).isFile())) {
              add(lines[0].n, "blocked-by", `The blocker \`${n}\` is not a file in the folder of this report, so /build cannot read it`, "name a ticket file that exists, relative to this file. A tracker reference such as `#12` does not work in a local file.");
            }
          }
        }
      }
    }
  }
  if (state === "needs-info") {
    const note = notes.at(-1);
    if (!note) {
      add(labelLine, "notes", "The issue is `needs-info` and has no Triage Notes", "post Triage Notes from BRIEF.md, with the AI line above the heading.");
    } else if (!sectionHasItem(note, /^What we still need/i, LIST_ITEM)) {
      add(note.line, "notes", "The Triage Notes have no question under \"What we still need\"", "add at least one specific question for the reporter as a list item.");
    }
  }
  if (state === "wontfix") {
    if (!issue.closed) {
      add(issue.statusLine ?? labelLine, "closed", "The issue is `wontfix` and is still open", issue.local ? "set `Status: closed` after the Triage Decision." : "close the issue after you post the Triage Decision.");
    }
    const decision = decisions.at(-1);
    const dline = decision ? blockLine(decision, DECISION) : null;
    const value = dline ? dline.t.match(DECISION)[1] : "";
    if (!decision || value === "") {
      add(decision?.line ?? labelLine, "decision", "The issue is `wontfix` and has no Triage Decision with a `Decision:` line", "post a Triage Decision from BRIEF.md with `Decision: wontfix, <already implemented | rejected bug | rejected enhancement>`.");
    } else if (!/already implemented|rejected bug|rejected enhancement/i.test(value)) {
      add(decision.line, "decision", `The \`Decision:\` line \`${value}\` names none of the three wontfix cases`, "write `Decision: wontfix, <already implemented | rejected bug | rejected enhancement>`.");
    } else if (/rejected enhancement/i.test(value)) {
      const text = decision.body.map((l) => l.t).join("\n");
      const refs = [...text.matchAll(/\.out-of-scope\/[\w.-]+\.md/g)].map((m) => m[0]);
      if (refs.length === 0) {
        add(decision.line, "out-of-scope", "The rejected enhancement names no `.out-of-scope/<concept>.md` file", "write or update the file as OUT-OF-SCOPE.md says, and name it in the Triage Decision.");
      } else {
        for (const r of refs) {
          if (!existsSync(resolve(issue.root ?? ".", r))) {
            add(decision.line, "out-of-scope", `The Triage Decision names \`${r}\`, which does not exist`, "write that file, or fix the name in the Triage Decision.");
          }
        }
      }
    }
  }
  for (const p of issue.extra ?? []) problems.push(p);
  return problems;
}

/** Read one local report file into the issue shape. */
export function localIssue(path, text, root = ".") {
  const lines = scan(text);
  const prose = lines.filter((l) => !l.fence);
  const extra = [];
  const statusLines = prose.filter((l) => STATUS.test(l.t));
  const labelLines = prose.filter((l) => LABELS.test(l.t));
  let closed = false;
  if (statusLines.length !== 1) {
    extra.push({ line: statusLines[1]?.n ?? 1, rule: "status", message: statusLines.length === 0 ? "The file has no `Status:` line" : `The file has ${statusLines.length} \`Status:\` lines`, fix: "keep one `Status: open` or `Status: closed` line near the top." });
  }
  if (statusLines.length >= 1) {
    const v = statusLines[0].t.match(STATUS)[1].toLowerCase();
    if (v !== "open" && v !== "closed") {
      extra.push({ line: statusLines[0].n, rule: "status", message: `\`Status: ${v}\` is not open or closed`, fix: "write `Status: open` or `Status: closed`. The triage state goes on the `Labels:` line." });
    }
    closed = v === "closed";
  }
  if (labelLines.length !== 1) {
    extra.push({ line: labelLines[1]?.n ?? 1, rule: "labels", message: labelLines.length === 0 ? "The file has no `Labels:` line" : `The file has ${labelLines.length} \`Labels:\` lines`, fix: "keep one `Labels:` line near the top, such as `Labels: bug, needs-info`." });
  }
  const raw = labelLines.length ? labelLines[0].t.match(LABELS)[1] : "";
  const labels = raw.split(",").map((s) => s.replace(/`/g, "").trim()).filter((s) => s && s.toLowerCase() !== "none");
  let commentsLine = 0;
  for (const l of prose) if (/^#{1,6}\s+Comments\s*$/i.test(l.t)) commentsLine = l.n;
  return {
    name: path,
    dir: dirname(resolve(path)),
    local: true,
    root,
    labels,
    closed,
    labelLine: labelLines[0]?.n ?? 1,
    statusLine: statusLines[0]?.n,
    blockedBy: prose.filter((l) => BLOCKED_BY.test(l.t)).map((l) => ({ n: l.n, value: l.t.match(BLOCKED_BY)[1].trim() })),
    blocks: findBlocks(text).map((b) => ({ ...b, outside: b.line <= commentsLine || commentsLine === 0 })),
    extra,
  };
}

/** Read one tracker issue (parsed JSON) into the issue shape. Throws InputError on a bad shape. */
export function jsonIssue(obj, fallbackName = "issue", root = ".") {
  if (obj === null || typeof obj !== "object" || Array.isArray(obj)) throw new InputError("The JSON is not an issue object");
  if (!Array.isArray(obj.labels)) throw new InputError("The issue JSON has no `labels` list");
  if (typeof obj.state !== "string") throw new InputError("The issue JSON has no `state` text");
  const comments = obj.comments ?? obj.notes;
  if (!Array.isArray(comments)) throw new InputError("The issue JSON has no `comments` list");
  const labels = obj.labels.map((l) => (typeof l === "string" ? l : l?.name)).filter((l) => typeof l === "string");
  const state = obj.state.toLowerCase();
  if (!["open", "opened", "closed", "merged"].includes(state)) throw new InputError(`The issue state \`${obj.state}\` is not open, opened, closed or merged`);
  const blocks = [];
  comments.forEach((c, i) => {
    const body = typeof c === "string" ? c : c?.body;
    if (typeof body !== "string") return;
    for (const b of findBlocks(body)) blocks.push({ ...b, line: i + 1 });
  });
  const name = obj.number !== undefined ? `#${obj.number}` : obj.iid !== undefined ? `#${obj.iid}` : fallbackName;
  return { name, local: false, root, labels, closed: state === "closed" || state === "merged", labelLine: 0, blocks, extra: [] };
}

/**
 * Read a label mapping table. Returns a Map from the tracker label (lower case) to its role.
 * A row is `| <role> | <label> | ... |`. Rows whose first cell is not a known role are skipped,
 * so the header and the separator row do not count. A row whose label is empty maps nothing.
 */
export function parseLabelMap(text) {
  const roles = new Set([...CATEGORIES, ...STATES, ...PRIORITIES].map((r) => r.toLowerCase()));
  const map = new Map();
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*\|([^|]*)\|([^|]*)\|/);
    if (!m) continue;
    const clean = (c) => c.replace(/`/g, "").trim();
    const role = clean(m[1]).toLowerCase();
    const label = clean(m[2]);
    if (!roles.has(role) || label === "") continue;
    const canonical = [...CATEGORIES, ...STATES, ...PRIORITIES].find((r) => r.toLowerCase() === role);
    map.set(label.toLowerCase(), canonical);
  }
  return map;
}

/** Replace each mapped tracker label with its role. A label with no mapping stays as it is. */
export function applyLabelMap(labels, map) {
  return labels.map((l) => map.get(l.toLowerCase()) ?? l);
}

export function formatProblem(name, p) {
  return `${name}:${p.line}  ${p.rule}  ${p.message}. Fix: ${p.fix}`;
}

function readInput(arg) {
  try {
    return arg === "-" ? readFileSync(0, "utf8") : readFileSync(resolve(arg), "utf8");
  } catch (e) {
    throw new InputError(`Cannot read ${arg === "-" ? "stdin" : arg} (${e.code ?? e.message})`);
  }
}

export function run(argv, { root = process.cwd() } = {}) {
  const out = [];
  const err = [];
  let json = null;
  let labelsArg = null;
  const files = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "-h" || a === "--help") return { code: EXIT.OK, out: [USAGE], err };
    if (a === "--json") {
      if (json !== null || argv[i + 1] === undefined) {
        err.push(`--json needs one file or \`-\`. Fix: run with \`--json <file>\` or \`--json -\`.`, USAGE);
        return { code: EXIT.USAGE, out, err };
      }
      json = argv[++i];
      continue;
    }
    if (a === "--labels") {
      if (labelsArg !== null || argv[i + 1] === undefined) {
        err.push(`--labels needs one file. Fix: run with \`--labels ${LABEL_MAP_FILE}\`.`, USAGE);
        return { code: EXIT.USAGE, out, err };
      }
      labelsArg = argv[++i];
      continue;
    }
    if (a.startsWith("-")) {
      err.push(`Unknown option ${a}. Fix: use only \`--json\` and \`--labels\`.`, USAGE);
      return { code: EXIT.USAGE, out, err };
    }
    files.push(a);
  }
  if ((json === null) === (files.length === 0)) {
    err.push("Give report files or one `--json` input, not both and not neither. Fix: pass the report paths, or `--json <file>`.", USAGE);
    return { code: EXIT.USAGE, out, err };
  }
  const issues = [];
  let labelMap = new Map();
  try {
    const mapPath = labelsArg !== null ? resolve(root, labelsArg) : resolve(root, LABEL_MAP_FILE);
    if (labelsArg !== null || existsSync(mapPath)) {
      let text;
      try {
        text = readFileSync(mapPath, "utf8");
      } catch (e) {
        throw new InputError(`Cannot read the label mapping ${mapPath} (${e.code ?? e.message})`, `pass a readable label mapping with \`--labels <file>\`, or fix ${LABEL_MAP_FILE}`);
      }
      labelMap = parseLabelMap(text);
    }
    if (json !== null) {
      let parsed;
      const text = readInput(json);
      try {
        parsed = JSON.parse(text);
      } catch (e) {
        throw new InputError(`The input is not JSON (${e.message})`);
      }
      const list = Array.isArray(parsed) ? parsed : [parsed];
      if (list.length === 0) throw new InputError("The JSON list is empty");
      list.forEach((o, i) => issues.push(jsonIssue(o, `issue ${i + 1}`, root)));
    } else {
      for (const f of files) issues.push(localIssue(f, readInput(f), root));
    }
  } catch (e) {
    if (!(e instanceof InputError)) throw e;
    err.push(`${e.message}. Fix: ${e.fix}.`);
    return { code: EXIT.INPUT, out, err };
  }
  let count = 0;
  for (const issue of issues) {
    issue.labels = applyLabelMap(issue.labels, labelMap);
    for (const p of checkIssue(issue)) {
      out.push(formatProblem(issue.name, p));
      count++;
    }
  }
  out.push(`${issues.length} issue(s) checked, ${count} problem(s).`);
  return { code: count === 0 ? EXIT.OK : EXIT.PROBLEMS, out, err };
}

/** True when this file is the script that node started. Compares real paths, so a symlink to it still runs. */
function isMain() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  const r = run(process.argv.slice(2));
  for (const l of r.out) console.log(l);
  for (const l of r.err) console.error(`triage-check: ${l}`);
  process.exitCode = r.code;
}
