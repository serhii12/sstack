/** Writes that are hidden inside other shell syntax. Each %s is replaced by one BASE_WRITES entry. */
export const WRAPPERS = [
  ["bash -c", (cmd) => `bash -c "${cmd}"`],
  ["sh -c", (cmd) => `sh -c '${cmd}'`],
  ["nested bash -c", (cmd) => `bash -c "bash -c '${cmd}'"`],
  ["eval", (cmd) => `eval "${cmd}"`],
  ["after &&", (cmd) => `true && ${cmd}`],
  ["after ;", (cmd) => `true; ${cmd}`],
  ["after ||", (cmd) => `false || ${cmd}`],
  ["after a pipe", (cmd) => `echo hi | ${cmd}`],
  ["after a newline", (cmd) => `true\n${cmd}`],
  ["in $()", (cmd) => `echo $(${cmd})`],
  ["in backticks", (cmd) => `echo \`${cmd}\``],
  ["in a group", (cmd) => `{ ${cmd}; }`],
  ["behind sudo", (cmd) => `sudo ${cmd}`],
  ["behind env", (cmd) => `env A=1 ${cmd}`],
  ["in an if", (cmd) => `if true; then ${cmd}; fi`],
  ["in a heredoc fed to bash", (cmd) => `bash <<'EOF'\n${cmd}\nEOF`],
];

